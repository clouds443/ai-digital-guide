def _join_paths(*paths):
    joined = []
    for path in paths:
        for coord in path:
            if not coord:
                continue
            item = [round(float(coord[0]), 6), round(float(coord[1]), 6)]
            if joined and abs(joined[-1][0] - item[0]) < 0.000001 and abs(joined[-1][1] - item[1]) < 0.000001:
                continue
            joined.append(item)
    return joined



def get_route_definition(route_id):
    route_id = str(route_id or "").strip()
    for route in list(DEFAULT_ROUTES) + [FAST_ROUTE]:
        if route.get("id") == route_id:
            return dict(route)
    return None


def build_route_map_by_id(route_id):
    route = get_route_definition(route_id)
    if not route:
        return None
    return build_route_map(route)


def build_route_map(route):
    route = dict(route or {})
    by_name, _ = _point_index()
    points = []
    skipped = []
    for order, stop in enumerate(route.get("stops") or [], start=1):
        point = by_name.get(stop)
        if not point:
            skipped.append(stop)
            continue
        item = dict(point)
        item["order"] = order
        item["stop"] = stop
        points.append(item)

    polyline = [[point["lng"], point["lat"]] for point in points]
    walk_polyline = _build_walk_polyline(points, polyline)
    bounds_points = list(points) + [{"lng": item[0], "lat": item[1]} for item in walk_polyline]
    return {
        "id": route.get("id", ""),
        "name": route.get("name", ""),
        "duration": route.get("duration", ""),
        "summary": route.get("summary", ""),
        "stops": list(route.get("stops") or []),
        "points": points,
        "polyline": polyline,
        "walk_polyline": walk_polyline,
        "bounds": _bounds(bounds_points),
        "skipped_stops": skipped,
        "center": _center(points),
    }


def attach_route_map(route):
    item = dict(route or {})
    item["map"] = build_route_map(item)
    return item


def attach_route_maps(routes):
    return [attach_route_map(route) for route in routes or []]


def _coord_for_path_name(name, by_name):
    point = by_name.get(name)
    if point:
        return [point["lng"], point["lat"]]
    point = WALK_WAYPOINTS.get(name)
    if point:
        return list(point)
    return None


def _append_unique(target, coord):
    if not coord:
        return
    coord = [round(float(coord[0]), 6), round(float(coord[1]), 6)]
    if target and abs(target[-1][0] - coord[0]) < 0.000001 and abs(target[-1][1] - coord[1]) < 0.000001:
        return
    target.append(coord)


def _build_walk_polyline(points, fallback_polyline):
    if len(points) < 2:
        return list(fallback_polyline or [])
    by_name, _ = _point_index()
    path = []
    for start, end in zip(points, points[1:]):
        start_name = start["name"]
        end_name = end["name"]
        segment_coords = WALK_SEGMENT_COORDS.get((start_name, end_name))
        if segment_coords is None:
            reverse_coords = WALK_SEGMENT_COORDS.get((end_name, start_name))
            segment_coords = list(reversed(reverse_coords)) if reverse_coords else None
        if segment_coords is not None:
            for coord in segment_coords:
                _append_unique(path, coord)
            continue
        names = WALK_SEGMENTS.get((start_name, end_name))
        if names is None:
            reverse = WALK_SEGMENTS.get((end_name, start_name))
            names = list(reversed(reverse)) if reverse else [start_name, end_name]
        for name in names:
            _append_unique(path, _coord_for_path_name(name, by_name))
    return path if len(path) > len(fallback_polyline or []) else list(fallback_polyline or [])


def _bounds(points):
    if not points:
        return {
            "southwest": list(MAP_CENTER),
            "northeast": list(MAP_CENTER),
        }
    lngs = [point["lng"] for point in points]
    lats = [point["lat"] for point in points]
    return {
        "southwest": [round(min(lngs) - 0.0008, 6), round(min(lats) - 0.0008, 6)],
        "northeast": [round(max(lngs) + 0.0008, 6), round(max(lats) + 0.0008, 6)],
    }


def _center(points):
    if not points:
        return list(MAP_CENTER)
    lng = sum(point["lng"] for point in points) / float(len(points))
    lat = sum(point["lat"] for point in points) / float(len(points))
    return [round(lng, 6), round(lat, 6)]

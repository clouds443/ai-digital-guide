def _point_index():
    by_name = {}
    by_id = {}
    for order, item in enumerate(SCENIC_MAP_POINTS, start=1):
        point = dict(item)
        point["order"] = order
        by_name[point["name"]] = point
        by_id[point["id"].upper()] = point
        if point["name"].startswith("灵山"):
            by_name[point["name"].replace("灵山", "", 1)] = point
    return by_name, by_id


def map_config():
    key = (os.getenv("AMAP_JS_KEY") or "").strip()
    security = (os.getenv("AMAP_JS_SECURITY_CODE") or "").strip()
    payload = {
        "ok": bool(key),
        "amap_key": key,
        "security_js_code": security,
        "center": list(MAP_CENTER),
        "zoom": MAP_ZOOM,
        "pitch": MAP_PITCH,
        "view_mode": "3D",
    }
    if not key:
        payload["error"] = "未配置 AMAP_JS_KEY，3D 地图将使用本地路线示意降级展示。"
    elif not security:
        payload["warning"] = "未配置 AMAP_JS_SECURITY_CODE，高德 JSAPI 可能拒绝加载。"
    return payload


